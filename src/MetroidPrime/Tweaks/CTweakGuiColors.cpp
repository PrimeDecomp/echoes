CTweakGuiColors::SVisorColorScheme
CTweakGuiColors::GetVisorColorScheme(CSamusHud::EHudState hudState) const {
  switch (hudState) {
  case CSamusHud::kHS_Combat:
  default:
    return SVisorColorScheme(mData->combatHudColorScheme);
  case CSamusHud::kHS_Echo:
    return SVisorColorScheme(mData->echoHudColorScheme);
  case CSamusHud::kHS_Scan:
    return SVisorColorScheme(mData->scanHudColorScheme);
  case CSamusHud::kHS_Dark:
    return SVisorColorScheme(mData->darkHudColorScheme);
  case CSamusHud::kHS_Ball:
    return SVisorColorScheme(mData->ballHudColorScheme);
  }
}
